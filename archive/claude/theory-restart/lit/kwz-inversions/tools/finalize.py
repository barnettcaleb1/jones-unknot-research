import json, sys
from collections import Counter
d = json.load(open(sys.argv[1])); paper = json.load(open(sys.argv[2]))
def P(dct): return {int(e): c for e, c in dct.items()}
def padd(p, e, c):
    p[e] = p.get(e, 0) + c
    if p[e] == 0: del p[e]
def pmul(p, r):
    out = {}
    for e1, c1 in p.items():
        for e2, c2 in r.items(): padd(out, e1 + e2, c1 * c2)
    return out
def psub(p, r):
    out = dict(p)
    for e, c in r.items(): padd(out, e, -c)
    return out
bad = []; stats = Counter(); arc_only = []; widths = Counter(); jvals = {}
spec_len = Counter(); rat_len = Counter(); rat_ngen = Counter()
for r in d['records']:
    dec = r['decategorified']; kh = r['khtpp']
    Vinf = P(dec['V_tauinf'])
    assert len(Vinf) == 1 and list(Vinf.values()) == [1], (r['name'], Vinf)
    e = list(Vinf)[0]; assert e % 24 == 0
    j = e // 24; jvals[r['name']] = j
    k = r['rational_component']['slope_k']
    Pk = P(r['P_kappa']); eta_t = P(dec['eta_over_universal'])
    lhs = pmul(eta_t, {8: 1, 0: -1})
    rhs = psub(pmul(pmul(Pk, {-3: -1}), {8: 1, 0: -1}), {})
    rat = {}
    padd(rat, 24 * j + 1 + 2 * k, 1); padd(rat, 24 * j + 1, -1)
    for ee, c in rat.items(): padd(rhs, ee, c)
    if lhs != rhs: bad.append(r['name'])
    for c in kh['Khr_components']:
        if c['type'] == 'special': spec_len[(c['length_khtpp'], c['n_generators'], c['khtpp_slope'], c['delta_kind'])] += 1
        elif c['type'] == 'rational': rat_len[(c['length_khtpp'], c['delta_kind'])] += 1; rat_ngen[(k, c['n_generators'])] += 1
        else: stats['unrecognized Khr component'] += 1
    if kh['n_BNr_compact'] == 0: arc_only.append(r['name'])
    r['decategorified']['j'] = j
    r['decategorified']['closed_formula_holds'] = (r['name'] not in bad)
    r['khtpp']['BNr_arc_printed_as_two_chains'] = (kh['n_BNr_arcs'] != 1)
print('closed formula fails for:', bad)
print('special descriptors (length, ngens, slope, delta kind):', spec_len.most_common())
print('rational descriptors (length, delta kind):', rat_len.most_common())
print('rational n_generators by k:', sorted(rat_ngen.items()))
print('unrecognized:', stats)
print('BNr = arc only:', arc_only)
print('j histogram:', sorted(Counter(jvals.values()).items()))
