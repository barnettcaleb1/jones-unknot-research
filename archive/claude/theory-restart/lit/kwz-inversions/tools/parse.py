import re, sys, json
from fractions import Fraction
from collections import defaultdict
src = sys.argv[1]; out = sys.argv[2]
summ = open(src + '/computations/summary').read().splitlines()
grad = open(src + '/computations/gradings').read().splitlines()

# --- summary: \myrow{<prefix>}{<name>}{<k>}{<n>}{}
summary = {}
order = []
for line in summ:
    m = re.match(r'\\myrow\{(.*?)\}\{(\d+)_\{(\d+)\}(?:\^\{(.*?)\})?\}\{(-?\d+)\}\{(\d+)\}\{\}', line)
    if not m:
        continue
    pre, c, idx, sup, k, n = m.groups()
    knot = f'{c}_{idx}'
    summary[(knot, sup)] = dict(k=int(k), n=int(n), highlighted=bool(pre.strip()))
    order.append((knot, sup))

# --- gradings: blocks starting with %<name>, with \mynode{x}{y}{mult}
blocks = []
cur = None
for line in grad:
    m = re.match(r'%(\d+)_\{(\d+)\}(?:\^\{(\d)\})?\s*$', line)
    if m:
        cur = dict(knot=f'{m.group(1)}_{m.group(2)}', inv=m.group(3), nodes=[], grid=None)
        blocks.append(cur); continue
    for mm in re.finditer(r'\\mynode\{\s*(-?\d+)\s*\}\{\s*(-?\d+)\s*\}\{\s*(\d+)\s*\}', line):
        cur['nodes'].append(tuple(int(t) for t in mm.groups()))
    mm = re.search(r'\\mygrid\{\s*(-?\d+)\s*\}\{\s*(-?\d+)\s*\}\{\s*(-?\d+)\s*\}\{\s*(-?\d+)\s*\}', line)
    if mm:
        cur['grid'] = tuple(int(t) for t in mm.groups())

def poly_str(p):
    # p: dict exponent->coeff
    if not any(p.values()): return '0'
    return ' + '.join(f'{c}*q^{e}' for e, c in sorted(p.items()) if c).replace('+ -', '- ')

records = []
problems = []
for b in blocks:
    knot, inv = b['knot'], b['inv']
    if (knot, inv) in summary: s = summary[(knot, inv)]; star = False
    elif (knot, '\\star') in summary: s = summary[(knot, '\\star')]; star = True
    elif (knot, None) in summary: s = summary[(knot, None)]; star = False
    else: s = None; problems.append(('no summary', knot, inv))
    comps = []
    P = defaultdict(int)       # sum mult * (-1)^(a-1/2) q^(2(a+b))
    chi_delta = 0              # sum mult * (-1)^(b-1/2)
    hpoly = defaultdict(int)   # Poincare polynomial in h only (Watson's Z-grading u)
    for (x, y, mult) in b['nodes']:
        a = Fraction(2*x+1, 2); bb = Fraction(2*y+1, 2)
        qc = int(2*(a+bb))
        sign = -1 if ((x) % 2) else 1          # (-1)^(a-1/2) = (-1)^x
        P[qc] += sign*mult
        chi_delta += mult * (-1 if (y % 2) else 1)
        for dh in (-2, 0, 1, 3):               # h = a + {-5/2,-1/2,1/2,5/2} = x + {-2,0,1,3}
            hpoly[x+dh] += mult
        comps.append(dict(type='special', curve='s_2(infty)', slope='1/0', length=2, multiplicity=mult,
                          tex_node=[x, y], kappa_shift_h=float(a), kappa_shift_delta=float(bb),
                          kappa_summand_delta=float(bb),
                          kappa_summand_h=[x-2, x, x+1, x+3],
                          kappa_summand_q=[qc-5, qc-1, qc+1, qc+5]))
    n_from_grad = sum(c['multiplicity'] for c in comps)
    deltas = sorted({c['kappa_shift_delta'] for c in comps})
    rec = dict(name=knot + (f'^{inv}' if inv else ''), knot=knot, inversion=(int(inv) if inv else None),
               crossings=int(knot.split('_')[0]),
               rational_component=dict(type='rational', curve='r_1(k)', slope_k=(s['k'] if s else None), length=1,
                                       bigrading='not given in the paper'),
               n_special=(s['n'] if s else None), n_special_from_gradings=n_from_grad,
               summary_row_shared_by_both_inversions=star,
               special_components=comps,
               dim_kappa=4*n_from_grad,
               kappa_delta_support=deltas,
               kappa_delta_width=int(deltas[-1]-deltas[0])+1,
               kappa_delta_gradings_contiguous=(len(deltas)==int(deltas[-1]-deltas[0])+1),
               chi_delta_kappa_over_4=chi_delta,
               check_abs_chi_delta_equals_abs_k_over_4=(s is not None and abs(chi_delta)*4==abs(s['k'])),
               P_kappa={str(e): c for e, c in sorted(P.items()) if c},
               P_kappa_str=poly_str(P),
               P_kappa_is_zero=(not any(P.values())),
               P_kappa_at_q_eq_1=sum(P.values()),
               kappa_poincare_in_h={str(e): c for e, c in sorted(hpoly.items())},
               tex_grid=b['grid'])
    if s is not None and s['n'] != n_from_grad: problems.append(('n mismatch', knot, inv, s['n'], n_from_grad))
    if not rec['check_abs_chi_delta_equals_abs_k_over_4']: problems.append(('chi_delta mismatch', knot, inv, chi_delta, s))
    records.append(rec)

meta = dict(
  source='arXiv:2104.13592v1 (Kotelskiy-Watson-Zibrowius, Khovanov homology and strong inversions), TeX source files computations/summary (Table 1) and computations/gradings (Section 5 table); both are auto-generated by kht++ and \\input into main.tex',
  coefficients='F_2',
  conventions=dict(
    naming='K^i = i-th strong inversion on the Rolfsen knot K in the numbering of Sakuma 1986; knots without superscript have a unique strong inversion. Chirality follows Sakuma\'s table (3_1 is the LEFT-hand trefoil, rational slope -4).',
    tangle='T_{K,h} is the preferred representative: tau(infty) = unknot, tau(0) <-> Seifert longitude, S^3_{p/q}(K) = Sigma(S^3, tau(p/q)), tau(p/q) = T_{K,h} glued to Q_{-p/q}.',
    Khr='Theorem 4.1: Khr(T_{K,h}) = r_1(k) union n copies of s_2(infty), k in 4Z, n>0. k = slope_k, n = n_special.',
    kappa='kappa(K,h) = HF(a(0), special components) = direct sum over special components i of h^{a_i} delta^{b_i} V_kappa, where V_kappa is 4-dimensional, supported in delta = 0, q = -5,-1,+1,+5 (hence h = q/2 - delta = -5/2,-1/2,1/2,5/2).',
    gradings='KWZ conventions: delta + h = q/2 (q integer-valued, twice Watson\'s quantum grading; delta has the opposite sign to Watson\'s delta = u - q). A TeX entry \\mynode{x}{y}{m} is a grey box [x-1,x] x [y-1,y] in a picture whose origin offset makes its centre (a,b) = (x+1/2, y+1/2); it stands for m summands h^{x+1/2} delta^{y+1/2} V_kappa. Checked against the worked example kappa(4_1^1) = h^{2.5} delta^{5.5} V + h^{6.5} delta^{4.5} V in Section 5.',
    derived='Fields computed by the digest author, not printed in the paper: kappa_summand_h/q (the four generators of each summand), P_kappa = sum_i (-1)^{a_i - 1/2} q^{2(a_i+b_i)} (so that the bigraded Euler characteristic sum (-1)^h q^{q-grading} of kappa equals P_kappa(q) * (q^{-5} + q^{-1} - q - q^{5})), chi_delta_kappa_over_4 = sum_i (-1)^{b_i - 1/2}, whose absolute value must equal |k|/4 by the determinant argument after Conjecture 4.6.'),
  not_available='The paper does not print the bigrading of the rational component r_1(k), nor BNr(T_{K,h}), nor tangle diagrams/PD codes for the 138 tangles.',
  counts=dict(strong_inversions=len(records), summary_rows=len(order)))
json.dump(dict(meta=meta, inversions=records), open(out, 'w'), indent=1)
print('records', len(records), 'summary rows', len(order), 'problems', problems)
