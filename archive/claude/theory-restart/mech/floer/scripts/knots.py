# Floer data (|m|, D') with m = slope of the essential component of the HRW curve = 2tau - sign(tau) for thin knots.
# rank HF^(S^3_{p/q}) = |p - q m| + q D'  for p/q != m.
def floer(knot):
    det, sig = DET_SIG[knot]
    if knot == '8_19':   # T(3,4): L-space knot, genus 3: m = 2g-1 = 5, D' = 5
        return 5, 5, 'Lspace'
    if knot == '9_42':   # HFK^ rank 9 = 1 + two unit squares, tau = 0 (sigma = 2 is NOT -2tau here)
        return 0, 4, 'thick'
    t = sig // 2
    if t == 0:
        return 0, (det - 1)//2, 'thin'
    return 2*t - 1, (det + 2*t - 3)//2, 'thin'
def arf(knot):
    det, _ = DET_SIG[knot]
    return 0 if det % 8 in (1, 7) else 1
