#!/usr/bin/env python3
"""Exact check of Theorem A in the Temperley-Lieb model (no kht++ involved).
State space: crossingless matchings of {top,0,1,2,3,4} (5 states).  E_1 = (top 0)(1 4)(2 3) = state after r1.r2.
Letters (kht++ quotient of a half-diagram letter):  Y = y0.y1.y1.y0, y = x0.x1.x1.x0, X = x2.x1.x3.x2, x = y2.y1.y3.y2.
Functional phi: cup u0, then coefficient of e_0 = (top b3)(b1 b2).
f(w) = phi(w E_1) (Laurent polynomial in A);  g(w) = (1 0) rho(w) (1 0)^T in t = A^-4.
Claim: f(w) = c(w) g(w), c multiplicative with c(Y) = f(Y), c(X) = f(X) units.
Dimension argument: f/c - g is a matrix coefficient of a representation of dimension <= 5 + 2 = 7, so equality on
all positive words of length <= 6 implies equality on the whole group generated by X, Y."""
import itertools, sys
from reflib import *
LET = {'Y': 'y0.y1.y1.y0', 'y': 'x0.x1.x1.x0', 'X': 'x2.x1.x3.x2', 'x': 'y2.y1.y3.y2'}
def apply_word(vec, word, ntop=1):
    """apply a Morse word to a state vector"""
    if isinstance(word, str): word = parse_word(word)
    for (c, i) in word:
        new = {}
        def acc(st, pol):
            if not pol: return
            if st in new:
                r = padd(new[st], pol)
                if r: new[st] = r
                else: del new[st]
            else: new[st] = pol
        import reflib
        for st, pol in vec.items():
            if c in 'lr': acc(reflib._cap(st, ntop, i), pol)
            elif c == 'u':
                s2, loops = reflib._cup(st, ntop, i); acc(s2, pmul(pol, DELTA) if loops else pol)
            else:
                s2, loops = reflib._cup(st, ntop, i); s3 = reflib._cap(s2, ntop, i)
                pu = pmul(pol, DELTA) if loops else pol
                if c == 'x': acc(s3, pshift(pu, 1)); acc(st, pshift(pol, -1))
                else: acc(st, pshift(pol, 1)); acc(s3, pshift(pu, -1))
        vec = new
    return vec
E1 = bracket('r1.r2', 1)
assert len(E1) == 1
E0 = (3, 2, 1, 0)
def phi(vec):
    v = apply_word(vec, 'u0')
    return v.get(E0, {})
def t_to_A(p):   # t = A^-4
    return {-4 * e: v for e, v in p.items()}
def f(word):
    v = E1
    for L in word: v = apply_word(v, LET[L])
    return phi(v), v
cY = f('Y')[0]; cX = f('X')[0]
print('f(Y) =', pstr(cY, 'A'), '  f(X) =', pstr(cX, 'A'), '  f(y) =', pstr(f('y')[0], 'A'), '  f(x) =', pstr(f('x')[0], 'A'))
assert is_unit(cY) and is_unit(cX)
def unit_of(word):
    e = 0; s = 1
    (eY, sY), = [(k, v) for k, v in cY.items()]
    (eX, sX), = [(k, v) for k, v in cX.items()]
    for L in word:
        if L == 'Y': e += eY; s *= sY
        elif L == 'y': e -= eY; s *= sY
        elif L == 'X': e += eX; s *= sX
        else: e -= eX; s *= sX
    return {e: s}
def check(word):
    lhs = f(word)[0]
    rhs = pmul(unit_of(word), t_to_A(J_matrix(word)))
    return lhs == rhs
bad = []
n = 0
maxpos = int(sys.argv[1]) if len(sys.argv) > 1 else 10
maxmix = int(sys.argv[2]) if len(sys.argv) > 2 else 7
for L in range(0, maxpos + 1):
    for w in itertools.product('XY', repeat=L):
        n += 1
        if not check(''.join(w)): bad.append(''.join(w))
    if L == 6: print('positive words of length <= 6 checked:', n, ' failures:', len(bad), '  (this is the rigorous part)')
print('positive words of length <=', maxpos, 'checked:', n, ' failures:', len(bad))
n2 = 0; bad2 = []
for L in range(0, maxmix + 1):
    for w in itertools.product('XYxy', repeat=L):
        n2 += 1
        if not check(''.join(w)): bad2.append(''.join(w))
print('all words in X,Y,x,y (not nec. reduced) of length <=', maxmix, 'checked:', n2, ' failures:', len(bad2))
print('failures:', bad[:10], bad2[:10])
# span of the orbit of E_1 (number of states that ever occur) and the invariance statements used in the report
states = set()
for L in range(0, 6):
    for w in itertools.product('XYxy', repeat=L):
        states |= set(f(''.join(w))[1].keys())
print('states occurring in the orbit of E_1:', len(states), sorted(states))
