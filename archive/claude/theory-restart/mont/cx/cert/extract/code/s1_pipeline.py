"""S1 pipeline: covector coincidences U1 ~ U2 (engineB/bottom_orbit.py, MAXDEPTH 8) -> closures s.l1.l1.U1^-1.U2.u2.u2;
dedupe (free reduction), exact V_K of the ORIGINAL diagram, word reduction + certification."""
import sys, json, time, gzip
from collections import Counter, defaultdict
from multiprocessing import Pool
sys.path.insert(0, '/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/cert/extract/code')
import rules, reduce as R, vk, certify_lib as C
OUT = '/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/cert/extract/'
def freered(w):
    out = []
    for a in w:
        if out and out[-1] == -a: out.pop()
        else: out.append(a)
    return tuple(out)
def work(item):
    key, w = item
    res = C.certify_word(w, budget=3000)
    hw0 = C.halfword(w)
    res['V_original_exact'] = (vk.VK(hw0) == {0: 1})
    res['ncross_original'] = vk.ncross(hw0)
    return key, res
if __name__ == '__main__':
    d = json.load(open(OUT + 'data/s1_rehits_d8_s11.json'))
    reh = d['rehits']
    groups = defaultdict(list)
    for dep, u1, u2 in reh:
        w = freered(rules.inv(rules.enc(u1)) + rules.enc(u2))
        groups[w].append((dep, u1, u2))
    print('S1 re-hits', len(reh), 'distinct freely reduced closure words', len(groups), flush=True)
    items = [(w, w) for w in groups]
    t0 = time.time()
    with Pool(8) as pool:
        results = pool.map(work, items, chunksize=200)
    print('reduced in', round(time.time() - t0, 1), 's', flush=True)
    stats = Counter(); statsd = defaultdict(Counter); resid = []; certs = []
    for (w, res) in results:
        prov = groups[w]
        st = res['status']; stats[st] += 1
        for dep, u1, u2 in prov: statsd[dep][st] += 1
        if not res['V_original_exact']: stats['ALARM_original_V_ne_1'] += 1
        certs.append({'word': rules.dec(w), 'status': st, 'reduced': res['reduced'], 'moves': res['moves'],
                      'ncross_original': res['ncross_original'], 'ncross_reduced': res.get('ncross_reduced'),
                      'prov': [{'depth': dep, 'U1': u1, 'U2': u2} for dep, u1, u2 in prov]})
        if st != 'CERT_c_empty' and st != 'CERT_a_TS24':
            resid.append({'halfword': C.halfword(w), 'reduced_halfword': C.halfword(rules.enc(res['reduced'])),
                          'ncross_original': res['ncross_original'], 'ncross_reduced': res.get('ncross_reduced'),
                          'status': st, 'V_K_exact_original_is_1': res['V_original_exact'],
                          'provenance': [{'script': 'engineB/bottom_orbit.py (regenerated by s1_regen.py)', 'MAXDEPTH': 8,
                                          'depth': dep, 'U1': u1, 'U2': u2} for dep, u1, u2 in prov]})
    print('distinct-word status', dict(stats))
    print('by depth (re-hit multiplicity):', {k: dict(v) for k, v in sorted(statsd.items())})
    json.dump(resid, open(OUT + 'data/s1_stage1_residue.json', 'w'), indent=0)
    with gzip.open(OUT + 'data/s1_certificates.jsonl.gz', 'wt') as f:
        for c in certs: f.write(json.dumps(c) + '\n')
    json.dump({'rehits': len(reh), 'distinct_words': len(groups), 'status_distinct': dict(stats),
               'status_by_depth_rehits': {k: dict(v) for k, v in statsd.items()}}, open(OUT + 'data/s1_stage1_counts.json', 'w'), indent=1)
