"""S2 pipeline: survivors of s2_regen.py (zeta_7 & zeta_10 units) -> exact J (engineB/fastJ.py == lp.J) -> J = 1 set;
dedupe by the word W = V.U; |W| in {13,14} = S2 proper (|W| <= 12: exact V_K check of the TS24 claim, bonus);
word reduction + certification (certify_lib).  usage: s2_pipeline.py D1 D2 NPROC"""
import sys, json, time, gzip, multiprocessing as mp
from collections import Counter, defaultdict
sys.path.insert(0, '/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/engineB')
sys.path.insert(0, '/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/cert/extract/code')
import fastJ, rules, certify_lib as C, vk
OUT = '/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/cert/extract/'
def work(W):
    Wl = W.split('.') if W else []
    J = fastJ.J('l1.l1', Wl, 'u2.u2')
    if J != {0: 1}: return W, {'J1': False, 'J': sorted(J.items()) if J else None}
    w = rules.enc(Wl)
    if len(w) <= 12:
        hw = C.halfword(w); nc = vk.ncross(hw); V = vk.VK(hw)
        st = 'CERT_a_TS24_original' if (nc <= 24 and V == {0: 1}) else 'ALARM'
        return W, {'J1': True, 'status': st, 'ncross_original': nc}
    res = C.certify_word(w, budget=3000)
    res['J1'] = True; res['ncross_original'] = vk.ncross(C.halfword(w))
    return W, res
if __name__ == '__main__':
    D1, D2, nproc = map(int, sys.argv[1:4])
    d = json.load(open(OUT + 'data/s2_survivors_%d_%d.json' % (D1, D2)))
    prov = defaultdict(list)
    for wt, wb in d['survivors']:
        W = '.'.join(x for x in (wt, wb) if x); prov[W].append((wt, wb))
    print('survivors', len(d['survivors']), 'distinct words', len(prov), flush=True)
    t0 = time.time()
    ctx = mp.get_context('fork')
    with ctx.Pool(nproc) as pool:
        results = pool.map(work, list(prov), chunksize=500)
    print('done', round(time.time() - t0, 1), 's', flush=True)
    stats = Counter(); bylen = defaultdict(Counter); resid = []; certs = []; nonunit = []
    for W, res in results:
        L = len(W.split('.')) if W else 0
        if not res['J1']:
            stats['J!=1'] += 1; bylen[L]['J!=1'] += 1
            if len(nonunit) < 50: nonunit.append((W, res['J']))
            continue
        st = res['status']; stats[st] += 1; bylen[L][st] += 1
        if L >= 13:
            certs.append({'word': W, 'status': st, 'reduced': res['reduced'], 'moves': res['moves'],
                          'ncross_original': res['ncross_original'], 'ncross_reduced': res.get('ncross_reduced'),
                          'prov': prov[W]})
            if st not in ('CERT_c_empty', 'CERT_a_TS24'):
                resid.append({'halfword': 's.l1.l1.' + W + '.u2.u2', 'reduced_halfword': C.halfword(rules.enc(res['reduced'])),
                              'ncross_original': res['ncross_original'], 'ncross_reduced': res.get('ncross_reduced'), 'status': st,
                              'provenance': [{'script': 'engineB/mitm.py + mitm_gated.py (regenerated by s2_regen.py)',
                                              'D1': D1, 'D2': D2, 'V_top': wt, 'U_bottom': wb} for wt, wb in prov[W]]})
    print('status', dict(stats)); print('by length', {k: dict(v) for k, v in sorted(bylen.items())})
    json.dump(resid, open(OUT + 'data/s2_stage1_residue.json', 'w'), indent=0)
    with gzip.open(OUT + 'data/s2_certificates.jsonl.gz', 'wt') as f:
        for c in certs: f.write(json.dumps(c) + '\n')
    json.dump({'survivors': len(d['survivors']), 'distinct_words': len(prov), 'status': dict(stats),
               'by_length': {k: dict(v) for k, v in bylen.items()}, 'nonunit_examples': nonunit},
              open(OUT + 'data/s2_stage1_counts.json', 'w'), indent=1)
