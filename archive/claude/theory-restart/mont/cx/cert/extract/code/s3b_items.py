"""Build S3b items: the knots at the 5 points k = -2..2 of every unit line found by s3_lines.py (exactly the points that
engineB/template_screen.py certified with kcert)."""
import json, sys
sys.path.insert(0, '/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/cert/extract/code')
from s3_lines import W_at
D = '/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/cert/extract/data/'
d = json.load(open(D + 's3_lines_6_6.json'))
items = []
for wt, wb, dd, m0, n0 in d['unit_lines']:
    for k in range(-2, 3):
        m, n = m0 + k * dd[0], n0 + k * dd[1]
        items.append(['.'.join(W_at(wt, wb, m, n)), {'script': 'engineB/template_screen.py 6 6 (regenerated by s3_lines.py)',
                                                     'V': wt, 'U': wb, 'direction': dd, 'offset': [m0, n0], 'k': k, 'm': m, 'n': n}])
json.dump({'items': items}, open(D + 's3b_items.json', 'w'))
print('unit lines', len(d['unit_lines']), 'items', len(items))
