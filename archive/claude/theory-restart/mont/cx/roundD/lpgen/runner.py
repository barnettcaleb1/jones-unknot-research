def mB_range(S,cl,fixk=None,M=6):
    """slice values m of mB = sigma.k - sigstar to examine for the d=0 cases"""
    if fixk is not None:
        return [sum(S[j].sig*v for j,v in fixk.items())-cl['sigstar']]
    sigs=set(c.sig for c in S)
    if not S: return [-cl['sigstar']]
    return [Fr(x,6)-0 for x in range(-6*M,6*M+1)]   # refined below
def slices(S,cl,fixk=None,M=8):
    if fixk is not None:
        return [sum(S[j].sig*v for j,v in fixk.items())-cl['sigstar']]
    if not S: return [-cl['sigstar']]
    # attainable values of sigma.k - sigstar: lattice generated by the sigma_j; scan a window
    den=1
    for c in S: den=den*c.sig.denominator//__import__('math').gcd(den,c.sig.denominator)
    return [Fr(x,den)-cl['sigstar'] for x in range(-M*den,M*den+1)]
def run_all(S,nmin,kmin=1,fixk=None,M=8,verbose=False,want=None,only=None):
    """returns dict (closure name, case name, slice) -> ('closed', cert) | ('open', (k,n)) | ('unverified',...)"""
    out={}
    for cl in lpg.closure_classes():
        if only and not only(cl): continue
        for nm,rows in lpg.case_rows(cl['p'],cl['q']):
            L=lpg.build(S,cl,rows,nmin,kmin=kmin,fixk=fixk)
            out[(cl['name'],nm,None)]=decide(L)
        for m in slices(S,cl,fixk,M):
            for nm,rows in lpg.case_rows(cl['p'],cl['q'],m=m):
                L=lpg.build(S,cl,rows,nmin,kmin=kmin,slice_m=m,nrule=cl['d0n'],fixk=fixk)
                out[(cl['name'],nm,m)]=decide(L)
    for tc in lpg.tie_classes():
        if only and not only(tc): continue
        L=lpg.build(S,dict(tc,end='top'),[],nmin,kmin=kmin,slice_m=0,nrule=tc['n'],fixk=fixk)
        out[(tc['name'],'tie',0)]=decide(L)
    return out
def decide(L):
    r=lpg.solve_primal(L)
    if r.status==2:
        f=lpg.farkas(L)
        if f is None or f=='unverified': return ('unverified',f)
        return ('closed',f)
    if r.status==0:
        k=[round(x,6) for x in r.x[:L.nk]]; n=round(r.x[L.iN],6)
        return ('open',(k,n))
    return ('err',r.status)
def summary(out):
    c=collections.Counter(v[0] for v in out.values())
    return dict(c)
def opens(out): return {k:v for k,v in out.items() if v[0]!='closed'}
