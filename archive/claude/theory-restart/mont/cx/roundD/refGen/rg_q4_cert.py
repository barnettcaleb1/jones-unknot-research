"""Q4 per-box certificate re-verification, SINGLE PROCESS (no pool), per-box result files (kind 'q4cert'), resumable.
Same 200 boxes as rg_q4_boxes.py (seed 20261117).  For each box: exact vector vc.vec(tree) -> MY end data -> must equal
C1's signature key (and lc-admissible, span a >= 1); MY generator (rg_gen.prove, n_min = 1) must prove every closure class;
C1's witnesses regenerated by C1's own search (read-only import) are re-checked EXACTLY in my framework (my rows, my n-rule,
my longest-path sup).  The lp.J vector check for the same boxes is task kind 'q4vec' in rg_robust.py."""
import sys, os, time
sys.path.insert(0, '/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/roundD/refGen')
import rg_robust as R
import rg_gen as G
import rg_q4_boxes as Q4
EA = '/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/engineA'
def main():
    os.makedirs(R.OUT, exist_ok=True)
    G.load_gtab(R.RG + 'rg_gtab.pkl')
    sys.path.insert(1, EA)
    import vc
    pick, Gr = R.q4_pick()
    t0 = time.time(); k = 0
    for x, key in pick:
        task = ('q4cert', x)
        if os.path.exists(R.fname(task)): continue
        T = Gr['trees'][x]
        a, b = vc.vec(T)
        Bd, sg, dl, lcok, spa = G.bdata_from_vec(a, b)
        res = dict(x=x, key_match=((Bd['top'], Bd['bot'], sg, dl) == key) and lcok and spa >= 1, span_a=spa,
                   tag=Gr['tags'][x])
        res.update(Q4.verify_sig(Bd, sg, dl, 1))
        R.save(task, res); k += 1
        if k % 20 == 0: print('  %d boxes, %.0fs' % (k, time.time() - t0), flush=True)
    status()
def status():
    pick, Gr = R.q4_pick()
    done = R.load_all()
    rs = [done[('q4cert', x)] for x, k in pick if ('q4cert', x) in done]
    print('q4cert: %d/200 boxes with results' % len(rs))
    print('  own B-data == C1 signature key (lc-admissible, span a >= 1):', sum(r['key_match'] for r in rs))
    print('  own generator proves ALL closure classes (V every odd |a|>=3, H every mu):', sum(not r['mine_open'] for r in rs))
    print('  C1 witnesses regenerated: %d; pass my exact re-check: %d; FAIL: %d; C1 rows != my rows: %d; C1 no witness: %d' % (
        sum(r['nwit'] for r in rs), sum(r['wit_ok'] for r in rs), sum(r['nbad'] for r in rs),
        sum(r['rows_diff'] for r in rs), sum(r['c1_none'] for r in rs)))
    import collections
    print('  by tag:', dict(collections.Counter(r['tag'] for r in rs)), ' min span a:', min((r['span_a'] for r in rs), default=None))
    for r in rs:
        if r['mine_open'] or r['nbad'] or not r['key_match']:
            print('  ISSUE', r['x'], r['mine_open'], r['wit_bad'], r['key_match'])
if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == 'status': status()
    else: main()
