NSUB=F.NSUB; S=F.S
def node_lp(cl,m,bounds):
    """bounds: list of (var, sense, value): var = j (class) or 'n'; sense 'le'/'ge'"""
    rows=dict(lpg.case_rows(cl['p'],cl['q']))['d=-1 e=-1']
    ex=[]; semx=[]
    for var,sense,val in bounds:
        if var=='n':
            ex.append(('ub',{NSUB:Fr(1) if sense=='le' else Fr(-1)},Fr(val) if sense=='le' else -Fr(val)))
            semx.append(dict(kind='ub',z=(0,)*6,cls={},n=1 if sense=='le' else -1,b=Fr(val) if sense=='le' else -Fr(val)))
        else:
            ex.append(('ub',{var:Fr(1) if sense=='le' else Fr(-1)},Fr(val) if sense=='le' else -Fr(val)))
            semx.append(dict(kind='ub',z=(0,)*6,cls={var:1 if sense=='le' else -1},n=0,b=Fr(val) if sense=='le' else -Fr(val)))
    L=lpg.build(S,cl,rows,0,kmin=1,slice_m=m,extra=ex)
    assert L.iN==NSUB
    rr,c3=F.gen_o3row(L,cl,m); L.add_eq(rr,c3)
    sem=F.sem_case_rows(cl,rows,None)+[dict(kind='eq',z=(0,)*6,cls=[F.SUB[j][1][2] for j in range(NSUB)],n=0,b=m+cl['sigstar'])]+[F.sem_order3(cl,m)]
    semub=[dict(kind='ub',z=(0,)*6,cls=[-1]*NSUB,n=0,b=-1)]+semx
    return L,sem,semub
def solve(cl,m,maxnodes=4000):
    t0=time.time(); stack=[[]]; nodes=0; leaves=0; rejected=0; feasible_int=None
    while stack:
        bounds=stack.pop(); nodes+=1
        if nodes>maxnodes: return dict(status='node limit',nodes=nodes,leaves=leaves)
        L,sem,semub=node_lp(cl,m,bounds)
        r=lpg.solve_primal(L)
        if r.status!=0:
            f=lpg.farkas(L)
            if not isinstance(f,tuple): return dict(status='no exact certificate at a leaf',bounds=bounds,lpstatus=r.status)
            u,w,val=f
            # u order: flows(19), case rows(3), slice(1), order-3(1); w: kmin, extra ub (bounds)
            ok,info=SC.check(sem+semub,list(u[19:])+list(w),NSUB,0)
            if not ok: rejected+=1; return dict(status='leaf certificate REJECTED',bounds=bounds,info=info)
            leaves+=1; continue
        x=r.x; frac=None; best=None
        for j in range(NSUB):
            v=x[j]; fp=v-math.floor(v)
            if 1e-7<fp<1-1e-7:
                sc=abs(fp-0.5)
                if best is None or sc<best: best=sc; frac=(j,v)
        if frac is None:
            v=x[NSUB]; fp=v-math.floor(v)
            if 1e-7<fp<1-1e-7: frac=('n',v)
        if frac is None:
            return dict(status='INTEGER POINT FOUND',k={F.SUB[j][0]:int(round(x[j])) for j in range(NSUB) if x[j]>0.5},n=x[NSUB],bounds=bounds)
        var,v=frac
        stack.append(bounds+[(var,'le',math.floor(v))]); stack.append(bounds+[(var,'ge',math.floor(v)+1)])
    return dict(status='INTEGER-INFEASIBLE (all leaves exactly certified)',nodes=nodes,leaves=leaves,time=round(time.time()-t0,1))
