"""ORDER-3 at the H mu=+-1 two-ended ties for ONE a-potential d2 box + n rational boxes (n = delta_D + 3 pinned), own data.
T3 (both ends r >= 3) needs the tau-law n = tau(B) - tau*; T2 (one end r = 2, D2 = tau* - tau(B) + n != 0 at the weak end)
needs D3 = D2 (1 - X1) there (sympy: c3 - c2 = (A3-B3) - (A2-B2)(1-A1)).  Per box and per weak end: LP over n pinned
rational boxes with rows P = P0 (mB = 0), Lambda pinned by D2, the D3 row; certificate generated by lpg (read-only) and
VERIFIED with the own semantic checker."""
import sys, pickle, collections
from fractions import Fraction as Fr
sys.path.insert(0,'/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/roundE/refM300/src')
import semcheck as SC, certcheck as CC, rlaurent as RL
import lpg, runner
HERE='/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/roundE/refM300/'
CD=CC.CD; W=CC.W
L=pickle.load(open('/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/engineC1/libA_jets.pkl','rb'))
items=[(tag,T,v) for (k,T,tag,tp,bt),v in zip(L['boxes'],L['vecs']) if tag!='R']
d2b=pickle.load(open('/Users/calebbarnett/jones-lanes/theory-restart/mont/cx/engineA/d2pos_boxes.pkl','rb')); items+=[('d2pos',b[2],b[1]) for b in d2b]
OPEN24={'d2_457','d2_459','d2_460','d2_497','d2_536','d2_565','d2_895','d2_902','d2_1232','d2_1238','d2_1247','d2_1494','d2_2557','d2_2780','d2_3075','d2_3076','d2_3077','d2_3933','d2_4277','d2_4643','d2_5150','d2_5152','d2_5153','d2_5154'}
res={}; cnt=collections.Counter(); pos=collections.Counter()
for mu in (1,-1):
    o,sgs,ds=W['H'][mu]
    taustar=sum(o[e][0][1]-o[e][1][1] for e in ('top','bot'))       # sum_ends l2(w1) - l2(w3)
    for lab in sorted(OPEN24,key=lambda s:int(s[3:])):
        key=CD[lab]['key']
        if key[2]!=sgs: continue
        n=int(key[3]-ds)
        if n<0: continue
        for x in CD[lab]['xs']:
            a,b=items[x][2]
            d3={}
            for end in ('top','bot'):
                da,ca,la=RL.logdata(a,end,3); db,cb,lb=RL.logdata(b,end,3); d3[end]=(la,lb)
            tau=sum(d3[e][1][1]-d3[e][0][1] for e in ('top','bot'))
            T3=(n==tau-taustar)
            verd=[]
            for end in ('top','bot'):
                p,q,_=o[end]; p1,p2,p3=p; q1,q2,q3=q
                D2=taustar-tau+n
                if D2==0: verd.append('D2=0'); continue
                ra,la,rb,lb=key[0] if end=='top' else key[1]
                l3qB=d3[end][1][2]-d3[end][0][2]
                # generator (lpg) -- same rows as tie3.py
                cl=dict(kind='H',name='tie3',end=end,p=(p1,p2),q=(q1,q2),sigstar=Fr(sgs))
                Lp=lpg.build([lpg.Cls(key,1,lab)],cl,[],n,kmin=0,fixk={0:1})
                Lp.lb[Lp.iN]=Fr(n); Lp.add_eq({Lp.iN:Fr(1)},Fr(n))
                Lp.add_eq(Lp.zrow((0,1,0,0)),p1-q1-rb+ra)
                Lp.add_eq(Lp.zrow((0,0,0,1)),p2-q2-(lb-la)-D2)
                import f1o3
                r={}
                for jj,s in enumerate(lpg.FINS):
                    if f1o3.FL3[s]: r[Lp.iG+jj]=-f1o3.FL3[s]
                for i,(aa,bb,l1,l2) in enumerate(lpg.EI):
                    if l1: r[Lp.iF+i]=r.get(Lp.iF+i,0)+D2*l1
                Lp.add_eq(r,D2*(1-p1-ra)-p3+q3+l3qB)
                d=runner.decide(Lp)
                if d[0]=='closed':
                    u,w,val=d[1]
                    sem=[dict(kind='eq',z=(0,)*6,cls=[1],n=0,b=1),          # k_D = 1 (fixk)
                         dict(kind='eq',z=(0,)*6,cls=[0],n=1,b=n),          # n pinned
                         dict(kind='eq',z=(0,1,0,0,0,0),cls=[0],n=0,b=p1-q1-rb+ra),
                         dict(kind='eq',z=(0,0,0,1,0,0),cls=[0],n=0,b=p2-q2-(lb-la)-D2),
                         dict(kind='eq',z=(D2,0,0,0,0,-1),cls=[0],n=0,b=D2*(1-p1-ra)-p3+q3+l3qB)]
                    ok,info=SC.check(sem,list(u[19:]),1,n)
                    verd.append('closed-VERIFIED' if ok else 'closed-REJECTED')
                else: verd.append(d[0])
            res[(mu,lab,x)]=(n,tau,T3,verd)
            cnt[(T3,tuple(verd))]+=1
            pe='top' if key[0][0]>0 else ('bot' if key[1][0]>0 else '?')
            oe=[e for e,v in zip(('top','bot'),verd) if not v.startswith('closed')]
            pos[(pe,tuple(oe))]+=1
print('instances',len(res))
for k,v in sorted(cnt.items(),key=str): print('  T3 possible=%s  T2 verdict (weak top, weak bot)=%s : %d'%(k[0],k[1],v))
print('  (a-positive end, open weak end(s)):',dict(pos))
pickle.dump(res,open(HERE+'tie3own.pkl','wb'))
