"""Exact certificate for all integer reaction powers on a trefoil-cover tangle.
The algebraic proof uses stdlib only. --diagrams additionally uses installed
Spherogram/Regina to regenerate actual diagrams and independent Jones values.
The A convention below is inverse to Spherogram's standard bracket convention.
"""
from pathlib import Path
import sys,json,argparse
ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'generic'))
# The file can also be run from this workspace's arbitrary current directory.
if not (ROOT/'generic').exists():
    ROOT=Path(__file__).resolve().parents[2]
    sys.path.insert(0,str(ROOT/'generic'))
from tangle_unit_check import add,mul,neg,shift,pairmul,power_b,DELTA,ONE
X=pairmul(pairmul(power_b(-1),power_b(-2)[::-1]),power_b(-3)[::-1])
R=power_b(6)[::-1]  # rational -1/6
N=lambda v:add(mul(DELTA,v[0]),v[1])
assert N(X)==ONE and N(R)=={18:1}
data={'convention':'A is inverse to Spherogram standard bracket A','X_vector':X,'R_minus_one_sixth_vector':R,'parities':{}}
# Physical Spherogram writhes: X_j=-j-4 for odd j, -j for even j;
# R_j=6-j for odd j, -6-j for even j. Thus Jones equality asks
# F_X,j = A^(30) F_R,j (odd), or A^(-18) F_R,j (even).
for parity,exponent in [('odd',30),('even',-18)]:
    v=tuple(add(a,neg(shift(b,exponent))) for a,b in zip(X,R))
    c0=mul(add(mul(DELTA,DELTA),{0:-1}),v[0])
    c1=add(v[0],mul(DELTA,v[1]))
    data['parities'][parity]={'C0':c0,'C1':c1,'normalization_exponent':exponent}
    if parity=='even':
        assert c0 and c1==neg(c0)
    else:
        assert (min(c0),max(c0),min(c1),max(c1))==(-14,50,-14,46)
# Numerator unknot forces rational comparator 1/k. Determinant matching is
# |1+j*k|=|6*j-1|, so k=-6 or j*(k-6)=-2.
exceptions=[(1,4),(2,5),(-1,8),(-2,7)]
data['determinant_exceptional_pairs']=exceptions
# Read physical writhes from the standard oriented diagrams for these four
# finite cases (also independently regenerated by --diagrams below).
writhes={(1,4):(-5,-5),(2,5):(-2,7),(-1,8):(-3,-7),(-2,7):(2,5)}
finite=[]
for j,k in exceptions:
    px=N(pairmul(X,power_b(j)))
    pr=N(pairmul(power_b(-k)[::-1],power_b(j)))
    wx,wr=writhes[j,k]
    vx=shift(px,3*wx,(-1)**wx)
    vr=shift(pr,3*wr,(-1)**wr)
    # Coefficients remain integral even when (-1)**negative exponent is float.
    vx={e:int(c) for e,c in vx.items()};vr={e:int(c) for e,c in vr.items()}
    finite.append({'j':j,'k':k,'writhe_X':wx,'writhe_R':wr,'Jones_X_A':vx,'Jones_R_A':vr,'equal':vx==vr})
assert [v['equal'] for v in finite]==[True,False,False,False]
data['exceptional_exact_checks']=finite
# Near-miss actual frame defect: first closures differ by four twists;
# second closures already agree in blackboard framing.
R4=power_b(-4)[::-1]
assert N(R4)=={-12:1}
assert N(pairmul(X,power_b(1)))==N(pairmul(R4,power_b(1)))
data['near_miss']={'formal_first_brackets':[N(X),N(R4)],'formal_second_bracket':N(pairmul(X,power_b(1))),'physical_writhe_pairs':[[0,4],[-5,-5]],'incompatible_frame_shift_magnitude':4}
parser=argparse.ArgumentParser();parser.add_argument('--diagrams',action='store_true');args=parser.parse_args()
if args.diagrams:
    sys.path.insert(0,str(ROOT/'braid_classification/packages'))
    from spherogram.links.tangles import RationalTangle
    from spherogram import Link
    import regina
    records=[]
    for name,t in [('X',RationalTangle(-1)+RationalTangle(1,2)+RationalTangle(1,3)),('R',RationalTangle(1,4))]:
        for j in [0,1]:
            l=(t+RationalTangle(j)).numerator_closure()
            original=l.PD_code();wr=l.writhe()
            rr=regina.Link.fromPD([[x+1 for x in c] for c in original])
            jon=str(rr.jones());l.simplify('global')
            records.append({'tangle':name,'probe':j,'PD_original':original,'writhe_original':wr,'Jones_Regina':jon,'PD_simplified':l.PD_code(),'crossings_simplified':len(l.crossings),'components':len(l.link_components)+l.unlinked_unknot_components})
    assert [r['crossings_simplified'] for r in records]==[0,5,0,5]
    assert all(r['components']==1 for r in records)
    assert set(map(tuple,records[1]['PD_simplified']))==set(map(tuple,records[3]['PD_simplified']))
    assert records[3]['PD_simplified']==Link(braid_closure=[-1]*5).PD_code()
    data['actual_diagrams']=records
    for j,k in exceptions:
        ts=[RationalTangle(j-1)+RationalTangle(1,2)+RationalTangle(1,3),RationalTangle(1,k)+RationalTangle(j)]
        assert tuple(t.numerator_closure().writhe() for t in ts)==writhes[j,k]
    # Check the orientation/parity recurrence at representative positive and
    # negative values, independently of the Laurent calculations above.
    for j in range(-10,11):
        ts=[RationalTangle(j-1)+RationalTangle(1,2)+RationalTangle(1,3),RationalTangle(-1,6)+RationalTangle(j)]
        expected=(-j-4,6-j) if j%2 else (-j,-6-j)
        assert tuple(t.numerator_closure().writhe() for t in ts)==expected
out=Path(__file__).with_suffix('.json')
out.write_text(json.dumps(data,indent=2)+'\n')
print('Certified: all j != 0, rational U-substrate comparison has exactly one Jones match, j=1,R=1/4; framing defects disagree by 4.')
